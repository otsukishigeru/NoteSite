async function saveToRedis(redisKey, entry) {
  const url   = process.env.KV_REST_API_URL;
  const token = process.env.KV_REST_API_TOKEN;
  if (!url || !token) return; // 環境変数未設定なら何もしない

  try {
    const value = encodeURIComponent(JSON.stringify(entry));
    await fetch(`${url}/lpush/${redisKey}/${value}`, {
      method: 'POST',
      headers: { 'Authorization': `Bearer ${token}` },
    });
    await fetch(`${url}/ltrim/${redisKey}/0/${MAX_CHAT_LOGS - 1}`, {
      method: 'POST',
      headers: { 'Authorization': `Bearer ${token}` },
    });
  } catch (err) {
    console.error('Redis save failed (non-fatal):', err.message);
  }
}

function jstNow() {
  return new Date(Date.now() + 9 * 60 * 60 * 1000)
    .toISOString()
    .replace('T', ' ')
    .slice(0, 19) + ' JST';
}

module.exports = async (req, res) => {
  // CORS ヘッダーの設定
  const allowedOrigins = [
    'https://chidouka-lab.com',
    'https://www.chidouka-lab.com',
    'http://chidouka-lab.com',
    'http://localhost:8090',
    'http://localhost:3000',
  ];

  const origin = req.headers.origin || '';
  if (allowedOrigins.includes(origin)) {
    res.setHeader('Access-Control-Allow-Origin', origin);
  } else {
    // Vercel プレビューや notesite-seven.vercel.app からも許可
    res.setHeader('Access-Control-Allow-Origin', '*');
  }

  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');

  // OPTIONS プリフライトリクエストの処理
  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  // POST 以外は拒否
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method Not Allowed' });
  }

  // API キーの確認
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    return res.status(500).json({ error: 'ANTHROPIC_API_KEY が設定されていません' });
  }

  // リクエストボディのパース
  let body;
  try {
    body = typeof req.body === 'string' ? JSON.parse(req.body) : req.body;
  } catch (e) {
    return res.status(400).json({ error: 'リクエストボディのパースに失敗しました' });
  }

  const userMessage = body && body.message;
  if (!userMessage) {
    return res.status(400).json({ error: 'message フィールドが必要です' });
  }

  const personaKey = (body && body.persona) || '1so';
  const persona = PERSONAS[personaKey];
  if (!persona) {
    return res.status(400).json({ error: '不明な persona です: ' + personaKey });
  }

  // Claude API へのリクエスト
  try {
    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': apiKey,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({
        model: persona.model,
        max_tokens: 2000,
        system: persona.systemPrompt,
        messages: [
          {
            role: 'user',
            content: userMessage,
          },
        ],
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error('Claude API error:', response.status, errorText);
      return res.status(response.status).json({
        error: 'Claude API リクエストに失敗しました',
        detail: errorText,
        status: response.status,
      });
    }

    const data = await response.json();

    // テキストブロックを抽出して返す
    const textContent = data.content
      ? data.content.filter((b) => b.type === 'text').map((b) => b.text).join('\n')
      : '';

    // ── Upstash Redis に対話ログを保存 ─────────────────────
    const now = Date.now();
    await saveToRedis(persona.redisKey, {
      id:       now,
      question: userMessage,
      answer:   textContent,
      date:     jstNow(),
    });

    return res.status(200).json({
      message: textContent,
      usage: data.usage || null,
    });
  } catch (err) {
    console.error('Unexpected error:', err);
    return res.status(500).json({
      error: 'サーバー内部エラーが発生しました',
      detail: err.message,
      stack: err.stack,
    });
  }
};
